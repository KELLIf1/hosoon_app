/// ثوابت القرآن الكريم الرياضية المستخدمة في محرك الحساب (hosn_engine).
///
/// هذا الملف Pure Dart بالكامل — لا يحتوي على أي منطق، فقط قيم خام (raw values).
/// أي دالة حسابية تحتاج هذه الأرقام يجب أن تستوردها من هنا، ولا يجوز تكرار
/// كتابة الأرقام مباشرة (magic numbers) في أي مكان آخر من المشروع.
library;

/// إجمالي عدد الأحزاب في القرآن الكريم كاملاً.
const int totalAhzab = 60;

/// عدد الأرباع في كل حزب (كل حزب ينقسم إلى 4 أرباع).
const int quartersPerHizb = 4;

/// عدد الصفحات في كل حزب (تقريبي، حسب طبعة المصحف المعتادة).
const int pagesPerHizb = 20;

/// إجمالي عدد الأرباع في القرآن الكريم كاملاً.
///
/// هذه القيمة مُشتقة رياضيًا من [totalAhzab] و [quartersPerHizb] وليست
/// رقمًا مستقلاً، لضمان مصدر حقيقة واحد (single source of truth):
/// إذا تغيّر أحد الثابتين الأساسيين مستقبلاً، تُحسب هذه القيمة تلقائيًا
/// بشكل صحيح دون الحاجة لتحديثها يدويًا.
const int totalQuarters = totalAhzab * quartersPerHizb;

/// إجمالي عدد صفحات القرآن الكريم، مُشتقة من [totalAhzab] و [pagesPerHizb].
const int totalPages = totalAhzab * pagesPerHizb;
